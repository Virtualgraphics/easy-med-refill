-- Easy MedRefill server schema (MariaDB). Minimal by design: the server
-- never holds a patient's medication list, only individual approved reorders.

CREATE TABLE IF NOT EXISTS reorder_requests (
  id                 CHAR(36)     NOT NULL,                      -- request id generated by the app
  reference          VARCHAR(16)  NOT NULL,                      -- short reference shown to practices
  confirm_token      CHAR(32)     NOT NULL,                      -- one-click confirmation link token
  status             ENUM('queued','sent','confirmed','overdue','cancelled') NOT NULL DEFAULT 'queued',
  language           CHAR(2)      NOT NULL DEFAULT 'de',
  patient_reference  VARCHAR(64)  NULL,
  provider_kind      ENUM('practice','pharmacy') NOT NULL,
  provider_name      VARCHAR(190) NOT NULL,
  provider_email     VARCHAR(190) NOT NULL,
  payload            LONGTEXT     NOT NULL,                      -- the minimal JSON payload as received
  message_subject    VARCHAR(255) NOT NULL,
  message_body       TEXT         NOT NULL,
  needed_by          DATE         NULL,
  follow_up_count    TINYINT UNSIGNED NOT NULL DEFAULT 0,
  last_error         VARCHAR(500) NULL,
  created_at         DATETIME     NOT NULL,
  sent_at            DATETIME     NULL,
  confirmed_at       DATETIME     NULL,
  follow_up_at       DATETIME     NULL,
  updated_at         DATETIME     NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_reference (reference),
  UNIQUE KEY uq_confirm_token (confirm_token),
  KEY idx_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS devices (
  id          CHAR(36)     NOT NULL,
  push_token  VARCHAR(255) NOT NULL,
  platform    ENUM('ios','android') NOT NULL,
  created_at  DATETIME     NOT NULL,
  updated_at  DATETIME     NOT NULL,
  PRIMARY KEY (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS shortages (
  source             VARCHAR(32)  NOT NULL,                      -- drugshortage_ch | bwl | simulated
  product_code       VARCHAR(32)  NOT NULL,                      -- GTIN or Pharmacode
  active_ingredient  VARCHAR(190) NULL,
  status             VARCHAR(64)  NULL,
  fetched_at         DATETIME     NOT NULL,
  PRIMARY KEY (source, product_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
