export const LATEST_SCHEMA_VERSION = migrations[migrations.length - 1].version;

/** Migrations that still have to run for a database at `currentVersion`. */
export function pendingMigrations(currentVersion: number): Migration[] {
  if (!Number.isInteger(currentVersion) || currentVersion < 0) {
    throw new Error(`Invalid schema version: ${currentVersion}`);
  }
  if (currentVersion > LATEST_SCHEMA_VERSION) {
    throw new Error(
      `Database schema version ${currentVersion} is newer than this app supports (${LATEST_SCHEMA_VERSION}).`,
    );
  }
  return migrations.filter((m) => m.version > currentVersion);
}
