/**
 * Versioned schema migrations for the on-device SQLite database.
 *
 * This module is pure (no Expo imports) so the SQL can be verified in unit
 * tests against Node's built-in SQLite. Each migration runs once, inside a
 * transaction, and bumps `PRAGMA user_version` to its version number.
 *
 * Rules:
 *  - Never edit a migration that has shipped. Add a new one.
 *  - Versions must be strictly increasing integers starting at 1.
 *  - Timestamps are ISO 8601 UTC strings. Calendar dates are 'YYYY-MM-DD'.
 *  - Booleans are INTEGER 0/1 with a CHECK constraint.
 *  - IDs are UUID strings generated by the app, so records can later be
 *    merged across devices (caregiver view) without renumbering.
 */

export interface Migration {
  readonly version: number;
  readonly name: string;
  readonly sql: string;
}

